/// Linear sensor calibration.
///
/// Fits `reference = slope * measured + intercept` through paired points,
/// reports the coefficient of determination (R²) and renders an
/// Arduino/ESP32-ready correction snippet. Pure Dart, no I/O.
library;

/// Result of a least-squares linear calibration.
class CalibrationResult {
  /// Slope of `reference = slope * measured + intercept`.
  final double slope;
  final double intercept;
  final double rSquared;
  final int pointCount;

  const CalibrationResult({
    required this.slope,
    required this.intercept,
    required this.rSquared,
    required this.pointCount,
  });
}

/// Fits a line through `(measured, reference)` pairs.
///
/// Returns `null` for fewer than two finite points or when all measured
/// values are identical (the slope is undefined).
CalibrationResult? linearCalibration(
  List<(double measured, double reference)> points,
) {
  final valid = [
    for (final point in points)
      if (point.$1.isFinite && point.$2.isFinite) point,
  ];
  if (valid.length < 2) return null;

  var sumX = 0.0;
  var sumY = 0.0;
  for (final (x, y) in valid) {
    sumX += x;
    sumY += y;
  }
  final meanX = sumX / valid.length;
  final meanY = sumY / valid.length;

  var numerator = 0.0;
  var denominator = 0.0;
  for (final (x, y) in valid) {
    final dx = x - meanX;
    numerator += dx * (y - meanY);
    denominator += dx * dx;
  }
  if (denominator == 0) return null;

  final slope = numerator / denominator;
  final intercept = meanY - slope * meanX;

  var residualSquares = 0.0;
  var totalSquares = 0.0;
  for (final (x, y) in valid) {
    final predicted = slope * x + intercept;
    final residual = y - predicted;
    residualSquares += residual * residual;
    final deviation = y - meanY;
    totalSquares += deviation * deviation;
  }
  final rSquared = totalSquares == 0
      ? (residualSquares == 0 ? 1.0 : 0.0)
      : 1 - residualSquares / totalSquares;

  return CalibrationResult(
    slope: slope,
    intercept: intercept,
    rSquared: rSquared.clamp(0.0, 1.0),
    pointCount: valid.length,
  );
}

/// Builds a copy-pasteable Arduino/ESP32 correction snippet.
String buildArduinoSnippet(
  CalibrationResult result, {
  String variable = 'rawValue',
}) {
  final slope = result.slope.toStringAsFixed(6);
  final intercept = result.intercept.toStringAsFixed(6);
  return '// Sensor calibration generated by SDS-Remote\n'
      '// Fit quality: R^2 = ${result.rSquared.toStringAsFixed(4)} '
      '(${result.pointCount} points)\n'
      'const float CAL_SLOPE = ${slope}f;\n'
      'const float CAL_INTERCEPT = ${intercept}f;\n'
      '\n'
      'float calibrate(float $variable) {\n'
      '  return CAL_SLOPE * $variable + CAL_INTERCEPT;\n'
      '}\n';
}
